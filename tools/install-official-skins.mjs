const ROOT = fileURLToPath(new URL('../', import.meta.url));
const MARKER = 'Generated by tools/install-official-skins.mjs';
export const DEFAULT_BACK_CHAR_IDS = Object.freeze(['char_4182_oblvns', 'char_4217_makoto']);
const readJson = async file => JSON.parse(await fs.readFile(file, 'utf8'));
const writeJson = (file, value) => fs.writeFile(file, JSON.stringify(value, null, 2) + '\n');
const exists = async file => { try { return (await fs.stat(file)).isFile(); } catch { return false; } };

/** Plan only actual battle models; Building/Spine models are never substituted for battle models.
 * [ASSUMED] Most outfits reuse Front for rear views to fit the existing 300 MB visual-set cap. The two integrated
 * operators retain true Back models by default; --back adds available Back models to the whole selected subset.
 * Original-resolution illustrations are an explicit, bounded subset option.
 */
export function planOfficialSkins(table, tree, charIds, { back = false, backCharIds = DEFAULT_BACK_CHAR_IDS, illustrations = false } = {}) {
  if (!table?.charSkins || !Array.isArray(tree?.tree) || tree.truncated) throw new Error('Incomplete official skin table or resource tree');
  const files = new Map(tree.tree.filter(row => row.type === 'blob' && typeof row.path === 'string'
    && /^[A-Za-z0-9_./-]+$/.test(row.path) && !row.path.split('/').some(p => p === '.' || p === '..'))
    .map(row => [row.path, row]));
  const wanted = new Set(charIds);
  const withBack = new Set(backCharIds);
  const skins = [], skipped = [];
  for (const row of Object.values(table.charSkins).sort((a, b) => a.skinId.localeCompare(b.skinId, 'en'))) {
    if (!wanted.has(row.charId) || !/^char_\d+_[a-z0-9]+@[A-Za-z0-9_@#+.\-]+$/.test(row.skinId)) continue;
    const stem = safeName(row.battleSkin?.skinOrPrefabId || row.skinId.replace('@', '_'));
    const base = `spine/${row.charId}/${stem}/`;
    const model = side => {
      let dir = base + side + '/';
      // Some official battle skeletons are directionless, e.g. Skadi the Corrupting Heart's skins.
      if (side === 'Front' && !files.has(`${dir}${stem}.skel`)) dir = base + 'Spine/';
      const skel = `${dir}${stem}.skel`, atlas = `${dir}${stem}.atlas`;
      if (!files.has(skel) || !files.has(atlas)) return null;
      const textures = [...files.keys()].filter(file => file.startsWith(dir) && file.endsWith('.png'));
      return textures.length ? { skel, atlas, textures } : null;
    };
    const front = model('Front');
    if (!front) { skipped.push({ skinId: row.skinId, reason: 'No complete battle Front/Spine model in resource index' }); continue; }
    const avatar = `avatar/ASSISTANT/${safeName(row.avatarId)}.png`;
    const portrait = `charpor/${safeName(row.portraitId)}.png`;
    const illust = `charpack/${safeName(row.portraitId)}.png`;
    const rear = back || withBack.has(row.charId) ? model('Back') : null;
    const selected = { front, ...(rear ? { back: rear } : {}) };
    const paths = [...new Set(Object.values(selected).flatMap(s => [s.skel, s.atlas, ...s.textures]))];
    for (const p of [avatar, portrait, ...(illustrations ? [illust] : [])]) if (files.has(p)) paths.push(p);
    const jobs = paths.map(rel => ({ rel, bytes: files.get(rel).size, sha: files.get(rel).sha,
      kind: rel.endsWith('.png') ? 'png' : rel.endsWith('.atlas') ? 'atlas' : 'skel', urls: [joinUrl(RAW.fexli, rel)] }));
    // Newer operators can have no small portrait in the fexli dump. Try the existing asset pipeline's source.
    const extraPortrait = !files.has(portrait) ? `portrait/${safeName(row.portraitId)}.png` : null;
    if (extraPortrait) jobs.push({ rel: extraPortrait, kind: 'png', urls: [joinUrl(RAW.yuanyan, `portrait/${row.portraitId}.png`)] });
    skins.push({ charId: row.charId, skinId: row.skinId, name: row.displaySkin?.skinName || row.skinId,
      group: row.displaySkin?.skinGroupName || '', models: selected, jobs,
      avatar: files.has(avatar) ? avatar : null, portrait: files.has(portrait) ? portrait : extraPortrait,
      illust: illustrations && files.has(illust) ? illust : null,
      bytes: jobs.reduce((sum, job) => sum + (job.bytes || 200000), 0) });
  }
  return { skins, skipped };
}

export function splitSkinPacks(skins, maxBytes = 140 * 1024 * 1024) {
  const batches = [];
  for (const skin of skins) {
    if (skin.bytes > maxBytes) throw new Error(`${skin.skinId} exceeds one plugin's installation budget`);
    let batch = batches.at(-1);
    if (!batch || batch.bytes + skin.bytes > maxBytes) { batch = { skins: [], bytes: 0 }; batches.push(batch); }
    batch.skins.push(skin); batch.bytes += skin.bytes;
  }
  return batches;
}

async function checkedCopy(cache, dir, job) {
  const bytes = await fs.readFile(path.join(cache, job.rel));
  if (!validate(job.kind, bytes)) throw new Error(`${job.rel}: invalid ${job.kind} asset`);
  if (job.sha) {
    const sha = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');
    if (sha !== job.sha) throw new Error(`${job.rel}: Git blob checksum mismatch; remove that cache file and retry`);
  }
  const target = path.join(dir, 'files', job.rel);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, bytes);
}

async function installPack(root, batch, index, cache, vanilla) {
  const id = `official-skins-${String(index + 1).padStart(2, '0')}`;
  const dir = path.join(root, '.cache/official-skins/stage', id);
  if (await exists(path.join(dir, 'plugin.json'))) {
    const marker = await fs.readFile(path.join(dir, 'README.md'), 'utf8');
    if (!marker.startsWith(MARKER)) throw new Error(`${id}: unmanaged staging folder exists`);
    await fs.rename(dir, path.join(root, '.cache/official-skins', `previous-stage-${id}-${Date.now()}`));
  }
  await fs.mkdir(dir, { recursive: true });
  const chars = {};
  for (const skin of batch.skins) {
    for (const job of skin.jobs) if (await exists(path.join(cache, job.rel))) await checkedCopy(cache, dir, job);
    const spine = {};
    for (const [side, model] of Object.entries(skin.models)) {
      const text = await fs.readFile(path.join(cache, model.atlas), 'utf8');
      const info = atlasInfo(text), sizes = new Map();
      for (const page of info.pages) {
        if (path.basename(page) !== page) throw new Error(`${model.atlas}: non-local atlas page`);
        const rel = path.posix.dirname(model.atlas) + '/' + page;
        if (!model.textures.includes(rel)) throw new Error(`${model.atlas}: unindexed atlas page ${page}`);
        const size = pngSize(await fs.readFile(path.join(cache, rel)));
        if (!size) throw new Error(`${rel}: invalid PNG`);
        sizes.set(page, size);
      }
      const norm = normalizeAtlas(text, { pageSize: page => sizes.get(page) || null });
      if (norm.missingSize.length) throw new Error(`${model.atlas}: incomplete texture sizes`);
      await fs.writeFile(path.join(dir, 'files', model.atlas), norm.text);
      spine[side] = { skel: 'files/' + model.skel, atlas: 'files/' + model.atlas,
        textures: info.pages.map(page => 'files/' + path.posix.dirname(model.atlas) + '/' + page) };
    }
    // Keep the chosen outfit on upward-facing units too. The existing asset helper otherwise inherits the
    // operator's DEFAULT Back model. Reusing Front costs no extra files; the core operators and --back use true rear views.
    spine.back ??= spine.front;
    const art = {};
    for (const key of ['avatar', 'portrait', 'illust']) if (skin[key] && await exists(path.join(cache, skin[key]))) art[key] = 'files/' + skin[key];
    (chars[skin.charId] ??= { skins: {} }).skins[skin.skinId] = { name: skin.name, group: skin.group, ...art, spine };
  }
  const types = new Set(Object.keys(chars).map(id => Object.hasOwn(vanilla.chars || {}, id) ? 'assets.override' : 'assets.add'));
  await writeJson(path.join(dir, 'plugin.json'), { manifest: 2, id, name: { zh: `官方时装资源 ${index + 1}`, en: `Official outfit assets ${index + 1}` },
    description: { zh: '本机安装的官方外观资源；每位玩家在干员调配、自选编队中独立选用。', en: 'Locally installed outfit assets; each seat chooses its own appearances.' },
    version: '1.0.0', app: '>=0.3.1 <0.4.0', api: 1, class: 'cosmetic', scope: ['room', 'personal'],
    authors: ['Stronghold-Protocol Community'], license: 'Proprietary', permissions: [...types], assets: 'assets.json' });
  await writeJson(path.join(dir, 'assets.json'), { chars });
  const trueBackCount = batch.skins.filter(skin => skin.models.back).length;
  await fs.writeFile(path.join(dir, 'README.md'), `${MARKER}\n\nGame assets © Hypergryph / Yostar and their respective rights holders. Local non-commercial use only; no game art is committed to Git.\n\nContains ${batch.skins.length} selectable outfits. Models: Front for all outfits, true Back for ${trueBackCount}; other rear views reuse the outfit's Front.\nEnable in room plugins or Settings → Cosmetic plugins, then choose outfits in operator loadout / DIY.\n`);
  const packed = packPlugin(dir, { vanilla: { manifest: vanilla, sha256: null }, dataDir: path.join(root, 'data') });
  const problems = [...packed.build.problems, ...(packed.check?.problems || [])];
  if (problems.length || !packed.wrote) throw new Error(`${id}: ${problems.join('; ')}`);
  const dest = path.join(root, 'plugins', id);
  await fs.mkdir(path.dirname(dest), { recursive: true });
  try {
    const old = await fs.readFile(path.join(dest, 'README.md'), 'utf8');
    if (!old.startsWith(MARKER)) throw new Error(`${id}: destination is not managed by this installer`);
    const replaced = path.join(root, 'plugins/_replaced', `${id}-${Date.now()}`);
    await fs.mkdir(path.dirname(replaced), { recursive: true });
    await fs.rename(dest, replaced);
  } catch (err) { if (err.code !== 'ENOENT') throw err; }
  await fs.rename(dir, dest);
  return { id, skins: batch.skins.length, assetBytes: packed.check.plugin.visual.bytes,
    files: Object.keys(packed.lock.files).length + 1,
    warnings: [...new Set([...packed.build.warnings, ...(packed.check?.warnings || [])])] };
}

export async function installOfficialSkins(root, opts = {}) {
  const log = opts.log || console.log;
  const policy = new MirrorPolicy({ source: opts.source || 'direct', log });
  const shared = { offline: !!opts.offline, refresh: !!opts.refreshIndex, timeoutMs: 30000, mirrorPolicy: policy, log };
  const table = await cachedJson({ ...shared, cacheFile: path.join(root, '.cache/gamedata/excel/skin_table.json'),
    url: RAW.gamedata + 'excel/skin_table.json', maxBytes: 32 * 1024 * 1024 });
  const tree = await cachedJson({ ...shared, cacheFile: path.join(root, '.cache/fexli-tree.json'),
    url: 'https://api.github.com/repos/fexli/ArknightsResource/git/trees/main?recursive=1', maxBytes: 64 * 1024 * 1024 });
  const vanilla = await readJson(path.join(root, 'data/assets.json'));
  const ids = opts.only?.length ? opts.only : [...Object.keys(vanilla.chars || {}), ...installedArtReferences(root)];
  const plan = planOfficialSkins(table, tree, ids, opts);
  const batches = splitSkinPacks(plan.skins);
  const bytes = batches.reduce((sum, b) => sum + b.bytes, 0);
  if (bytes > 285 * 1024 * 1024) throw new Error(`Selected outfits need ${(bytes / 1048576).toFixed(1)} MB; choose a smaller --only-operator subset to stay below the 300 MB visual-set limit`);
  log(`[skins] ${plan.skins.length} outfits, ${batches.length} plugins, estimated ${(bytes / 1048576).toFixed(1)} MB; ${plan.skipped.length} without a battle model`);
  if (opts.dryRun) return { outfits: plan.skins.length, bytes, skipped: plan.skipped, plugins: batches.map((b, i) => ({ id: `official-skins-${String(i + 1).padStart(2, '0')}`, skins: b.skins.length })) };
  const cache = path.join(root, '.cache/official-skins/files');
  const jobs = plan.skins.flatMap(skin => skin.jobs);
  if (opts.offline) {
    for (const job of jobs.filter(job => job.sha)) if (!await exists(path.join(cache, job.rel))) throw new Error(`--offline: missing ${job.rel}`);
  } else {
    const downloader = new Downloader({ root: cache, ledgerPath: path.join(root, '.cache/official-skins/ledger.json'),
      mirrorPolicy: policy, concurrency: opts.concurrency || 16, retries: 1, timeoutMs: 20000, log });
    await downloader.loadLedger();
    const results = await downloader.run(jobs, 'skins');
    for (const job of jobs.filter(job => job.sha)) {
      const result = results.get(job.rel);
      if (!['ok', 'skip'].includes(result?.status)) throw new Error(`${job.rel}: ${result?.error || result?.status}; rerun to resume`);
    }
  }
  const plugins = [];
  for (let i = 0; i < batches.length; i++) {
    const installed = await installPack(root, batches[i], i, cache, vanilla);
    plugins.push(installed); log(`[skins] installed ${installed.id}: ${installed.skins} outfits`);
  }
  const report = { outfits: plan.skins.length, operators: new Set(plan.skins.map(s => s.charId)).size,
    bytes: plugins.reduce((sum, plugin) => sum + plugin.assetBytes, 0), estimatedBytes: bytes,
    backModels: !!opts.back, trueBackOutfits: plan.skins.filter(skin => skin.models.back).length,
    trueBackOperators: [...new Set(plan.skins.filter(skin => skin.models.back).map(skin => skin.charId))],
    originalIllustrations: !!opts.illustrations, plugins, skipped: plan.skipped,
    tableSha256: createHash('sha256').update(JSON.stringify(table)).digest('hex'), treeSha: tree.sha };
  await writeJson(path.join(root, '.cache/official-skins/report.json'), report);
  return report;
}

async function main(args) {
  const opts = { only: [] };
  let root = ROOT;
  for (let i = 0; i < args.length; i++) {
    const [arg, inline] = args[i].split('=');
    const value = () => inline ?? args[++i];
    if (arg === '--root') root = path.resolve(value());
    else if (arg === '--only-operator') opts.only.push(value());
    else if (arg === '--asset-source') opts.source = value();
    else if (arg === '--concurrency') opts.concurrency = Number(value());
    else if (arg === '--offline') opts.offline = true;
    else if (arg === '--refresh-index') opts.refreshIndex = true;
    else if (arg === '--dry-run') opts.dryRun = true;
    else if (arg === '--back') opts.back = true;
    else if (arg === '--illustrations') opts.illustrations = true;
    else if (arg === '--help') { console.log('node tools/install-official-skins.mjs [--dry-run] [--offline] [--refresh-index] [--asset-source direct|mirror] [--concurrency 16] [--only-operator char_ID ...] [--back] [--illustrations] [--root checkout]'); return; }
    else throw new Error(`Unknown option ${arg}`);
  }
  console.log(JSON.stringify(await installOfficialSkins(root, opts), null, 2));
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href && !restartForEnvProxy()) {
  main(process.argv.slice(2)).catch(err => { console.error(`[skins] ${err.message}`); process.exitCode = 1; });
}
